import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { generateKeyPair } from 'jose';
import { JwtService } from '../../../src/modules/auth/jwt-service.js';
import { CredentialHasher } from '../../../src/modules/auth/credential-hasher.js';
import { RateLimiter, RATE_POLICY } from '../../../src/middleware/rate-limiter.js';
import { resolveSyncContext } from '../../../src/middleware/sync-auth-context.js';
import { SyntheticIdentityRepository } from '../../identity-persistence/support/synthetic-repository.js';
import { SyntheticCoordinator } from './coordinator.js';
const pair = await generateKeyPair('RS256', { modulusLength:2048 });
const config = { ...pair, mode:'isolated-test', algorithm:'RS256', issuer:'https://two-sides.test.invalid', audience:'two-sides-isolated-api', keyId:'sync-gate' };
const repository = new SyntheticIdentityRepository({ synthetic:true, coordinator:new SyntheticCoordinator() });
const service = new JwtService({ config, repository, version:2, hasher:new CredentialHasher(), limiter:new RateLimiter(), policy:RATE_POLICY });
const binding = { installationId:randomUUID(), localPlayerId:randomUUID(), bindingGeneration:1 };
const credential = randomBytes(32).toString('base64url');
const registered = await service.register({ registrationId:randomUUID(), credential, ...binding }, 'synthetic-gate');
const { accessToken } = await service.session({ technicalAccountId:registered.body.technicalAccountId, credential, ...binding }, 'synthetic-gate');
const principal = await service.authenticate(accessToken);
const context = await resolveSyncContext(principal, accessToken, repository);
assert.equal(context.localPlayerId, binding.localPlayerId); assert.equal(context.installationId, binding.installationId);
await repository.revokeIdentity(principal.id);
await assert.rejects(context.validate, error => error.status === 401);
console.log(JSON.stringify({ gate:'Authenticated-v2-binding', passed:true, revocationRejected:true }));
